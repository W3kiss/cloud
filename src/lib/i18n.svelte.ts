const DICTS: Record<LangId, Dict> = { ru: RU, en: EN, uk: UK, de: DE, es: ES, fr: FR, pl: PL, tr: TR };

/** Translate a key in the current language, falling back to Russian then the key. */
export function t(key: string): string {
  return DICTS[settings.lang]?.[key] ?? RU[key] ?? key;
}

/** Guess the initial language from the system locale. */
export function detectLang(): LangId {
  const code = (typeof navigator !== "undefined" ? navigator.language : "ru").slice(0, 2).toLowerCase();
  return LANGS.some((l) => l.id === code) ? (code as LangId) : "en";
}

export function applyLang(): void {
  if (typeof document !== "undefined") document.documentElement.lang = settings.lang;
}
